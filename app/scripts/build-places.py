#!/usr/bin/env python3
"""Builds app/public/places/<CC>.json — sea ports and airports per country — from public data.

Sources (download them next to this script, then run it):
  * UN/LOCODE (UNECE), seaports = locations whose function code has "1" in the first place:
      https://raw.githubusercontent.com/datasets/un-locode/main/data/code-list.csv
  * OurAirports (public domain), airports with an IATA code and scheduled flights:
      https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv
Re-run it to refresh the lists; the app only reads the JSON files.
"""
import csv, json, os, sys, collections
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else here
out = os.path.join(here, '..', 'public', 'places')
os.makedirs(out, exist_ok=True)
data = collections.defaultdict(lambda: {'sea': set(), 'air': set()})
for r in csv.DictReader(open(os.path.join(src, 'code-list.csv'), encoding='utf-8')):
    if (r['Function'] or '')[:1] == '1' and r['Status'] not in ('XX', 'RR') and r['Country']:
        data[r['Country']]['sea'].add((r['NameWoDiacritics'] or r['Name']).strip())
for r in csv.DictReader(open(os.path.join(src, 'airports.csv'), encoding='utf-8')):
    if r['type'] in ('large_airport', 'medium_airport') and r['iata_code'] and r['scheduled_service'] == 'yes' and r['iso_country']:
        name, city = r['name'].strip(), (r['municipality'] or '').strip()
        label = f"{name} ({r['iata_code']})" if not city or city.lower() in name.lower() else f"{city} — {name} ({r['iata_code']})"
        data[r['iso_country']]['air'].add(label)
codes = []
for cc, d in sorted(data.items()):
    if len(cc) != 2: continue
    codes.append(cc)
    with open(os.path.join(out, f'{cc}.json'), 'w', encoding='utf-8') as f:
        json.dump({'sea': sorted(d['sea']), 'air': sorted(d['air'])}, f, ensure_ascii=False, separators=(',', ':'))
with open(os.path.join(here, '..', 'src', 'lib', 'place-countries.ts'), 'w') as f:
    f.write('// Generated by scripts/build-places.py: countries that have ports or airports in public/places/.\n')
    f.write('export const PLACE_COUNTRIES = ' + json.dumps(codes) + ' as const\n')
print(len(codes), 'countries')
